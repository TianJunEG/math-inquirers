"""Generate term/l1/AUDIT_LNN.md (a draft with the rubric table filled from the validator) if it does not exist.

build.py calls this after a build; a draft contains 'TODO(author)' lines and the build exits non-zero until the author has
filled every judgement line (an existing audit without TODO(author) is never touched).
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import *  # noqa

CRITERIA = [  # (label, validator prefix)
    ('Schema valid (JSON Schema + key checks)', 'schema'),
    ('Every answer verified independently (verify/lNN_checks.py)', 'verify'),
    ('Online practice variants verified (expression, oracle, runner JS)', 'practice'),
    ('Timing: parts sum to 90, no part OVER, buffer, slow-class', 'timing'),
    ('Slides and script linked (each slide once, in its part)', 'link'),
    ('Tier counts and completeness (answer, hint, solution, mistakes)', 'tiers'),
    ('Neutral labels, no overclaims, no private chat', 'wording'),
    ('Recording cues short, with child action', 'rec'),
    ('Spare-time menu present', 'spare'),
    ('No copied contest text', 'copy'),
    ('Mascot used modestly', 'mascot'),
    ('Workbook page fill (model)', 'pages'),
    ('Real PDF page count and fill', 'outputs'),
    ('No template leak (other lesson titles, Lesson 1 text)', 'template leak'),
]
A = ['Low floor, high ceiling', 'Depth over speed', 'Generalise', 'Justify', 'Multiple paths', 'Challenge ladder', 'Student-led inquiry',
     'Complexity / context', 'Problem posing', 'Metacognition', 'Pacing / compacting', 'Extension, not acceleration']


def path(num): return os.path.join(L1, f'AUDIT_L{num}.md')


def is_draft(num):
    p = path(num)
    return os.path.exists(p) and 'TODO(author)' in open(p, encoding='utf-8').read()


def missing(num): return not os.path.exists(path(num))


def write_draft(d, passes, warns, fails):
    num = d['_num']
    rows = []
    for label, pre in CRITERIA:
        msgs = [m for m in passes + warns + fails if m.lower().startswith(pre)]
        bad = [m for m in fails if m.lower().startswith(pre)]
        wr = [m for m in warns if m.lower().startswith(pre)]
        res = 'FAIL' if bad else ('PASS with warning' if wr else ('PASS' if msgs else 'not run'))
        ev = (bad or wr or msgs or ['-'])[0].replace('|', '/')[:150]
        rows.append(f'| {label} | {res} | {ev} |')
    cri = '\n'.join(f'{i} {n}: TODO(author) score 0 to 2 and one line of evidence;' for i, n in enumerate(A, 1))
    txt = f"""# Self-audit: Level 1 Term {d['term']} Lesson {d['lesson_in_term']} ({d['title']})

DRAFT generated by `tools/audit.py` from the validator results of the last build. The table below is automatic; the author must replace every `TODO(author)` with an honest judgement (the build exits non-zero until none is left). Rubric: `docs/audit/reaudit_p1.md` instruments A and tier compliance, `AUTHORING.md` checklist.

## Automatic checklist

| Criterion | Result | Evidence |
|---|---|---|
""" + '\n'.join(rows) + f"""

Timing: script {d.get('_timing_total', (0, 0))[0] / 60:.1f} min of 90, slow-class {d.get('_timing_total', (0, 0))[1] / 60:.1f} min. Workbook fill (model): {', '.join(f'{f:.0%}' for f in d.get('_fills', []))}.

## Judgement lines (author)

- Tier principle (Start here approachable and not contest-style; Think harder = taught idea in a new setting; Go further = mastery plus extension): TODO(author)
- Age-appropriateness for 6 to 8 (reading load, one new idea, objects before symbols): TODO(author)
- Joining cold (Remember warm-up covers every prerequisite): TODO(author)
- Safeguarding and privacy consistent between script, slides and guide: TODO(author)
- Pictures and pages viewed at readable size, nothing clipped or overlapping: TODO(author)

## Instrument A (gifted-style, 0 to 2 each)

{cri}

Total: TODO(author) / 24

## Known limits

- Never trialled with children; times and difficulty are modelled. TODO(author): add lesson-specific limits.
"""
    open(path(num), 'w', encoding='utf-8').write(txt)
