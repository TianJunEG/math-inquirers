def _find_visual(blocks, kind='hundred'):
    out = []
    for b in blocks:
        if b['t'] == 'visual' and b['type'] == kind: out.append(b)
        if b['t'] == 'cols':
            for c in b['cols']: out += _find_visual(c, kind)
    return out


