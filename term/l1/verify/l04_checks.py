# ---------------------------------------------------------------- the model: a real number square

def make_grid(per=10, rows=10):
    return [[r * per + c + 1 for c in range(per)] for r in range(rows)]

GRID = make_grid()

def pos(n, grid=GRID):
    for r, row in enumerate(grid):
        if n in row:
            return r, row.index(n)
    raise ValueError(n)

def move(n, down=0, right=0, grid=GRID):
    """Move a counter on the square; refuses to leave it or to wrap round the end of a row."""
    r, c = pos(n, grid)
    r2, c2 = r + down, c + right
    assert 0 <= r2 < len(grid) and 0 <= c2 < len(grid[0]), f'{n} moved off the square'
    return grid[r2][c2]

def skip(start, step, upto):
    out, x = [], start
    while x <= upto:
        out.append(x); x += step
    return out

def gaps(seq):
    return [b - a for a, b in zip(seq, seq[1:])]

def grow_seq(first, n, gap0=1):
    """Sequence whose gaps are gap0, gap0+1, gap0+2, ..."""
    out, x, g = [first], first, gap0
    for _ in range(n - 1):
        x += g; g += 1; out.append(x)
    return out

def chain(a, b, n):
    """Each number after the first two is the sum of the two numbers before it."""
    out = [a, b]
    while len(out) < n:
        out.append(out[-1] + out[-2])
    return out

def interleave(first_up, step_up, first_down, step_down, n):
    """Two rules mixed in one list: odd places go up, even places go down."""
    ups, downs, out = first_up, first_down, []
    for i in range(n):
        if i % 2 == 0:
            out.append(ups); ups += step_up
        else:
            out.append(downs); downs -= step_down
    return out

def columns_of(nums):
    return sorted({pos(n)[1] + 1 for n in nums})


