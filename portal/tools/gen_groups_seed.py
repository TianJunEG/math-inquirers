#!/usr/bin/env python3
"""Generate supabase/seed_groups.sql from website/data/beta_schedule.json.
    python3 portal/tools/gen_groups_seed.py          # rewrite the file
    python3 portal/tools/gen_groups_seed.py --check  # exit 1 if the committed file is stale
Re-running the SQL is safe: it upserts groups but never touches seats already taken."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'website', 'data', 'beta_schedule.json')
OUT = os.path.join(HERE, '..', 'supabase', 'seed_groups.sql')

def q(s): return "'" + str(s).replace("'", "''") + "'"

def build():
    d = json.load(open(SRC, encoding='utf-8'))
    fee = int(round(d['price']['total'] * 100))
    rows = []
    for g in d['groups']:
        rows.append("  (%s, %d, %s, %s, %d, %s::jsonb, %s, %s, %s, %d)" % (
            q(g['id']), g['level'], q(g['name']), q(g['ages']), g['seats'], q(json.dumps(g['sessions'])),
            q(g['first']), q(g['last']), q(g['lessons'][0]['date']), fee))
    return ("-- GENERATED by portal/tools/gen_groups_seed.py from website/data/beta_schedule.json. Do not edit by hand.\n"
            "insert into public.groups (id, level, name, ages, seats, sessions, first_label, last_label, start_date, fee_cents) values\n"
            + ",\n".join(rows) + "\n"
            "on conflict (id) do update set level = excluded.level, name = excluded.name, ages = excluded.ages, seats = excluded.seats,\n"
            "  sessions = excluded.sessions, first_label = excluded.first_label, last_label = excluded.last_label,\n"
            "  start_date = excluded.start_date, fee_cents = excluded.fee_cents;\n")

if __name__ == '__main__':
    s = build()
    if '--check' in sys.argv:
        sys.exit(0 if os.path.exists(OUT) and open(OUT, encoding='utf-8').read() == s else 1)
    open(OUT, 'w', encoding='utf-8').write(s)
    print('wrote', OUT)
